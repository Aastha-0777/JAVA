package oop.abstraction;

public abstract class A {

	// Abstract Methods
	public abstract void test1();
	public abstract void test2();
	public abstract void test3();
	
	
	// Non-abstract Methods
	public void test4() {
		
		System.out.println("A : test4()");
		
	}
	
	public void test5() {
		
		System.out.println("A : test5()");
		
	}
	
}
