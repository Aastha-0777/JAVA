package oop.pureEncapsulation;

public class Products {
	
	private int pId;
	private String pName;
	private String pCatgr;

	//setters
	
	public void setPId(int pId) {
		
		this.pId = pId;
		
	}//end of setPId
	
	public void setPName(String pName) {
		
		this.pName = pName;
		
	}//end of setPName
	
	public void setPCatgr(String pCatgr) {
		
		this.pCatgr = pCatgr;
		
	}//end of setPCatgr
	
	//getters
	
	public int getPId() {
		
		return pId;
		
	}//end of getPId
	
	public String getPName() {
		
		return pName;
		
	}//end of getPName
	
	public String getPCatgr() {
		
		return pCatgr;
		
	}//end of getPCatgr
	
}
